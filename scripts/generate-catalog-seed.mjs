import {readFile, writeFile} from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const catalog = JSON.parse(await readFile(new URL('web-app/data/catalog.json', root), 'utf8'));
const literal = value => value == null ? 'null' : "E'" + String(value)
  .replaceAll('\\', '\\\\').replaceAll("'", "''")
  .replaceAll('\r', '\\r').replaceAll('\n', '\\n').replaceAll('\t', '\\t') + "'";
const json = value => literal(JSON.stringify(value)) + '::jsonb';
const statements = ['-- Generated by scripts/generate-catalog-seed.mjs. Existing records are never overwritten.', 'begin;'];
for (const [position, product] of catalog.products.entries()) {
  statements.push(`insert into public.catalog_products (id, position, data) values (${literal(product.id)}, ${position}, ${json(product)}) on conflict do nothing;`);
}
for (const [position, document] of catalog.documents.entries()) {
  statements.push(`insert into public.catalog_documents (id, position, data) values (${literal(document.id)}, ${position}, ${json(document)}) on conflict do nothing;`);
}
for (const [position, page] of catalog.pages.entries()) {
  statements.push(`insert into public.catalog_pages (document_id, page, position, data) values (${literal(page.document)}, ${page.page}, ${position}, ${json(page)}) on conflict do nothing;`);
}
statements.push(`insert into public.catalog_settings (id, terms, currency, price_note) values (true, ${literal(catalog.terms)}, ${literal(catalog.currency)}, ${literal(catalog.priceNote)}) on conflict do nothing;`, 'commit;', '');
await writeFile(new URL('supabase/seed.sql', root), statements.join('\n'));
console.log(`Prepared ${catalog.products.length} products, ${catalog.documents.length} documents and ${catalog.pages.length} pages.`);
